/**
 * Converts SVG or raw vector data URLs into standard high-resolution raster JPEG data URLs
 * to ensure 100% compatibility with jsPDF's addImage across all browsers.
 */
export async function ensureRasterDataUrl(dataUrl: string): Promise<string> {
  if (!dataUrl || typeof dataUrl !== 'string') return dataUrl;
  if (!dataUrl.startsWith('data:image/svg+xml') && !dataUrl.includes('image/svg+xml')) {
    return dataUrl;
  }
  return new Promise((resolve) => {
    try {
      const img = new Image();
      img.crossOrigin = 'anonymous';
      img.onload = () => {
        try {
          const canvas = document.createElement('canvas');
          canvas.width = img.naturalWidth || img.width || 1200;
          canvas.height = img.naturalHeight || img.height || 1650;
          const ctx = canvas.getContext('2d');
          if (ctx) {
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(0, 0, canvas.width, canvas.height);
            ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
            resolve(canvas.toDataURL('image/jpeg', 0.95));
            return;
          }
        } catch (e) {
          console.warn('Canvas conversion error in ensureRasterDataUrl:', e);
        }
        resolve(dataUrl);
      };
      img.onerror = (e) => {
        console.warn('SVG image load error in ensureRasterDataUrl:', e);
        resolve(dataUrl);
      };
      img.src = dataUrl;
    } catch {
      resolve(dataUrl);
    }
  });
}

/**
 * Captures the HTML form element using html2canvas with full sRGB sanitation
 * to prevent modern OKLCH/lab CSS color parser crashes.
 */
export async function captureFormToCanvas(formElement: HTMLElement): Promise<HTMLCanvasElement> {
  if (typeof document !== 'undefined' && document.fonts && document.fonts.ready) {
    try {
      await document.fonts.ready;
    } catch {
      // fallback
    }
  }

  // Ensure DOM rendering & signature overlay are fully drawn
  await new Promise((r) => setTimeout(r, 160));

  return html2canvas(formElement, {
    scale: 2, // 2x high-DPI resolution for crisp Korean text and signature
    useCORS: true,
    allowTaint: false,
    backgroundColor: '#ffffff',
    logging: false,
    scrollX: 0,
    scrollY: 0,
    windowWidth: 1200,
    windowHeight: 1600,
    imageTimeout: 15000,
    onclone: (clonedDoc, clonedElement) => {
      sanitizeClonedDocumentForHtml2canvas(clonedDoc, clonedElement);
    },
  });
}

/**
 * Generates a unified high-resolution multi-page PDF in the strict required sequence:
 * Page 1: 사회통합프로그램 연계 신청서 (Official Form Template)
 * Page 2: TOPIK 성적증명서 (Official TOPIK Score Report - Vector PDF or Image)
 * Page 3: 외국인등록증 — 앞면 + 뒷면 (Merged ARC on a single page)
 * Page 4+: 여권 (Passport pages, if uploaded)
 *
 * Utilizes pdf-lib to merge original vector PDF files (such as official TOPIK score PDFs
 * downloaded from topik.go.kr) with 100% vector sharpness, preventing blank pages.
 */
export async function generateMergedPdf({
  formElement,
  docs,
  formData,
}: GeneratePdfOptions): Promise<MergedPdfResult> {
  const mergedPdfDoc = await PDFDocument.create();

  // ==========================================
  // PAGE 1: 사회통합프로그램 연계 신청서 Template (Official Form with Signature)
  // ==========================================
  const formCanvas = await captureFormToCanvas(formElement);
  const formImgData = formCanvas.toDataURL('image/jpeg', 0.98);

  const formJsPdf = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
    compress: true,
  });
  const canvasRatio = formCanvas.height / formCanvas.width;
  const renderHeight = 210 * canvasRatio;
  if (renderHeight <= 297) {
    formJsPdf.addImage(formImgData, 'JPEG', 0, 0, 210, renderHeight, undefined, 'FAST');
  } else {
    const fitWidth = 297 / canvasRatio;
    const offsetX = (210 - fitWidth) / 2;
    formJsPdf.addImage(formImgData, 'JPEG', offsetX, 0, fitWidth, 297, undefined, 'FAST');
  }
  const formPdfBytes = formJsPdf.output('arraybuffer');
  const formPdfDoc = await PDFDocument.load(formPdfBytes);
  const [copiedFormPage] = await mergedPdfDoc.copyPages(formPdfDoc, [0]);
  mergedPdfDoc.addPage(copiedFormPage);

  // ==========================================
  // PAGE 2: TOPIK 성적증명서
  // ==========================================
  if (docs.topikCertList && docs.topikCertList.length > 0) {
    for (let i = 0; i < docs.topikCertList.length; i++) {
      const topikItem = docs.topikCertList[i];
      if (!topikItem?.dataUrl) continue;

      if (isPdfDataUrl(topikItem.dataUrl)) {
        try {
          const topikBytes = dataUrlToUint8Array(topikItem.dataUrl);
          const topikDoc = await PDFDocument.load(topikBytes, { ignoreEncryption: true });
          const indices = topikDoc.getPageIndices();
          const copiedPages = await mergedPdfDoc.copyPages(topikDoc, indices);
          for (const page of copiedPages) {
            mergedPdfDoc.addPage(page);
          }
        } catch (err) {
          console.error('Failed to parse uploaded TOPIK PDF with pdf-lib, falling back to raster:', err);
          const fallbackJsPdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
          fallbackJsPdf.setFontSize(12);
          fallbackJsPdf.setTextColor(15, 23, 42);
          fallbackJsPdf.text(
            `[첨부 1] 한국어능력시험(TOPIK) 성적증명서 사본 — ${formData.name || '신청인'}`,
            15,
            15
          );
          fallbackJsPdf.setFontSize(10);
          fallbackJsPdf.setTextColor(100, 116, 139);
          fallbackJsPdf.text(`(파일명: ${topikItem.name || 'topik_certificate.pdf'})`, 15, 25);
          const fbBytes = fallbackJsPdf.output('arraybuffer');
          const fbDoc = await PDFDocument.load(fbBytes);
          const [fbPage] = await mergedPdfDoc.copyPages(fbDoc, [0]);
          mergedPdfDoc.addPage(fbPage);
        }
      } else {
        // Image TOPIK (JPEG / PNG / SVG)
        const rasterTopikUrl = await ensureRasterDataUrl(topikItem.dataUrl);
        const topikJsPdf = new jsPDF({
          orientation: 'portrait',
          unit: 'mm',
          format: 'a4',
          compress: true,
        });

        topikJsPdf.setFontSize(10);
        topikJsPdf.setTextColor(100, 116, 139);
        topikJsPdf.text(
          `[첨부 1] 한국어능력시험(TOPIK) 성적증명서 사본 — ${formData.name || '신청인'}`,
          15,
          12
        );

        try {
          topikJsPdf.addImage(rasterTopikUrl, 'JPEG', 15, 16, 180, 265, undefined, 'FAST');
        } catch {
          try {
            topikJsPdf.addImage(rasterTopikUrl, 'PNG', 15, 16, 180, 265, undefined, 'FAST');
          } catch (imgErr) {
            console.warn('Failed to add TOPIK image to PDF page:', imgErr);
          }
        }

        const tBytes = topikJsPdf.output('arraybuffer');
        const tDoc = await PDFDocument.load(tBytes);
        const [tPage] = await mergedPdfDoc.copyPages(tDoc, [0]);
        mergedPdfDoc.addPage(tPage);
      }
    }
  }

  // ==========================================
  // PAGE 3: 외국인등록증 (앞면 + 뒷면 Merged on 1 Page)
  // ==========================================
  if (docs.arcFront && docs.arcBack) {
    const mergedArcDataUrl = await mergeArcFrontAndBack(
      docs.arcFront,
      docs.arcBack,
      formData.name
    );

    const arcJsPdf = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4',
      compress: true,
    });
    arcJsPdf.addImage(mergedArcDataUrl, 'JPEG', 0, 0, 210, 297, undefined, 'FAST');

    const arcBytes = arcJsPdf.output('arraybuffer');
    const arcDoc = await PDFDocument.load(arcBytes);
    const [arcPage] = await mergedPdfDoc.copyPages(arcDoc, [0]);
    mergedPdfDoc.addPage(arcPage);
  } else if (docs.arcFront) {
    const arcJsPdf = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4',
      compress: true,
    });
    arcJsPdf.setFontSize(11);
    arcJsPdf.setTextColor(15, 23, 42);
    arcJsPdf.text(`[첨부 2] 외국인등록증 사본 — ${formData.name || '신청인'}`, 15, 15);
    const rasterArcUrl = await ensureRasterDataUrl(docs.arcFront);
    try {
      arcJsPdf.addImage(rasterArcUrl, 'JPEG', 15, 25, 180, 115, undefined, 'FAST');
    } catch {
      arcJsPdf.addImage(rasterArcUrl, 'PNG', 15, 25, 180, 115, undefined, 'FAST');
    }

    const arcBytes = arcJsPdf.output('arraybuffer');
    const arcDoc = await PDFDocument.load(arcBytes);
    const [arcPage] = await mergedPdfDoc.copyPages(arcDoc, [0]);
    mergedPdfDoc.addPage(arcPage);
  }

  // ==========================================
  // PAGE 4+: 여권 (Passport pages if uploaded)
  // ==========================================
  if (docs.passportList && docs.passportList.length > 0) {
    for (let i = 0; i < docs.passportList.length; i++) {
      const pass = docs.passportList[i];
      if (!pass?.dataUrl) continue;

      if (isPdfDataUrl(pass.dataUrl)) {
        try {
          const passBytes = dataUrlToUint8Array(pass.dataUrl);
          const passDoc = await PDFDocument.load(passBytes, { ignoreEncryption: true });
          const indices = passDoc.getPageIndices();
          const copiedPages = await mergedPdfDoc.copyPages(passDoc, indices);
          for (const page of copiedPages) {
            mergedPdfDoc.addPage(page);
          }
        } catch (err) {
          console.error('Failed to parse uploaded Passport PDF with pdf-lib:', err);
        }
      } else {
        const passJsPdf = new jsPDF({
          orientation: 'portrait',
          unit: 'mm',
          format: 'a4',
          compress: true,
        });
        passJsPdf.setFontSize(10);
        passJsPdf.setTextColor(100, 116, 139);
        passJsPdf.text(
          `[첨부 3] 여권 사본 (${i + 1}/${docs.passportList.length}) — ${formData.name || '신청인'}`,
          15,
          12
        );

        const rasterPassUrl = await ensureRasterDataUrl(pass.dataUrl);
        try {
          passJsPdf.addImage(rasterPassUrl, 'JPEG', 15, 18, 180, 260, undefined, 'FAST');
        } catch {
          passJsPdf.addImage(rasterPassUrl, 'PNG', 15, 18, 180, 260, undefined, 'FAST');
        }

        const pBytes = passJsPdf.output('arraybuffer');
        const pDoc = await PDFDocument.load(pBytes);
        const [pPage] = await mergedPdfDoc.copyPages(pDoc, [0]);
        mergedPdfDoc.addPage(pPage);
      }
    }
  }

  const mergedBytes = await mergedPdfDoc.save();
  const createBlob = () => new Blob([mergedBytes.buffer as ArrayBuffer], { type: 'application/pdf' });

  return {
    output(type?: string): any {
      if (type === 'arraybuffer') {
        return mergedBytes.buffer;
      }
      return createBlob();
    },
    save(filename: string) {
      const blob = createBlob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      setTimeout(() => {
        try {
          document.body.removeChild(a);
          URL.revokeObjectURL(url);
        } catch {}
      }, 2000);
    },
    getBlob() {
      return createBlob();
    },
    getBytes() {
      return mergedBytes;
    },
  };
}

/**
 * Generates a single-page high-resolution PDF of only the official application form template
 */
export async function generateSingleFormPdf(
  formElement: HTMLElement
): Promise<jsPDF> {
  const pdf = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
    compress: true,
  });

  const pageWidth = 210;
  const pageHeight = 297;

  const formCanvas = await captureFormToCanvas(formElement);
  const formImgData = formCanvas.toDataURL('image/jpeg', 0.98);
  const canvasRatio = formCanvas.height / formCanvas.width;
  const renderHeight = pageWidth * canvasRatio;
  if (renderHeight <= pageHeight) {
    pdf.addImage(formImgData, 'JPEG', 0, 0, pageWidth, renderHeight, undefined, 'FAST');
  } else {
    const fitWidth = pageHeight / canvasRatio;
    const offsetX = (pageWidth - fitWidth) / 2;
    pdf.addImage(formImgData, 'JPEG', offsetX, 0, fitWidth, pageHeight, undefined, 'FAST');
  }
  return pdf;
}

