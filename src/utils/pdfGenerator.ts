/**
 * Checks if a given data URL contains PDF data.
 */
export function isPdfDataUrl(dataUrl?: string | null): boolean {
  if (!dataUrl || typeof dataUrl !== 'string') return false;
  const trimmed = dataUrl.trim().toLowerCase();
  return (
    trimmed.startsWith('data:application/pdf') ||
    trimmed.startsWith('data:application/x-pdf') ||
    trimmed.includes('application/pdf')
  );
}

/**
 * Converts a base64 Data URL to a Uint8Array byte array for pdf-lib.
 */
export function dataUrlToUint8Array(dataUrl: string): Uint8Array {
  const commaIndex = dataUrl.indexOf(',');
  const base64 = commaIndex >= 0 ? dataUrl.slice(commaIndex + 1) : dataUrl;
  const binaryString = atob(base64);
  const len = binaryString.length;
  const bytes = new Uint8Array(len);
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes;
}


/**
 * Offscreen canvas 2D context to convert any modern CSS color
 * (oklch, color(), lab, etc.) into standard hex or rgba strings.
 */
let colorCanvasCtx: CanvasRenderingContext2D | null = null;

function getColorCanvasCtx(): CanvasRenderingContext2D | null {
  if (typeof document === 'undefined') return null;
  if (!colorCanvasCtx) {
    const canvas = document.createElement('canvas');
    canvas.width = 1;
    canvas.height = 1;
    colorCanvasCtx = canvas.getContext('2d', { willReadFrequently: true });
  }
  return colorCanvasCtx;
}

const colorCache = new Map<string, string>();

/**
 * Converts modern CSS colors (such as OKLCH generated by Tailwind CSS v4)
 * to standard sRGB hex or rgba strings that html2canvas can parse without throwing errors.
 */
export function convertOklchToRgb(colorStr: string, fallback = '#000000'): string {
  if (!colorStr || typeof colorStr !== 'string') return fallback;
  const trimmed = colorStr.trim();
  if (
    trimmed === 'transparent' ||
    trimmed === 'rgba(0, 0, 0, 0)' ||
    trimmed === 'inherit' ||
    trimmed === 'initial'
  ) {
    return 'rgba(0, 0, 0, 0)';
  }
  if (
    trimmed.startsWith('#') ||
    trimmed.startsWith('rgb(') ||
    trimmed.startsWith('rgba(') ||
    trimmed.startsWith('hsl(') ||
    trimmed.startsWith('hsla(')
  ) {
    return trimmed;
  }

  if (colorCache.has(trimmed)) {
    return colorCache.get(trimmed)!;
  }

  const ctx = getColorCanvasCtx();
  if (ctx) {
    try {
      ctx.fillStyle = '#000000';
      ctx.fillStyle = trimmed;
      const res = ctx.fillStyle;
      if (res && res !== trimmed && (res.startsWith('#') || res.startsWith('rgb'))) {
        colorCache.set(trimmed, res);
        return res;
      }
    } catch {
      // ignore
    }
  }

  // Fallbacks for known Tailwind v4 neutrals if canvas conversion fails
  if (
    trimmed.includes('0.98') ||
    trimmed.includes('0.99') ||
    trimmed.includes('0.96') ||
    trimmed.includes('0.97')
  ) {
    return '#f8fafc';
  }
  if (trimmed.includes('0.9')) {
    return '#e2e8f0';
  }
  if (
    trimmed.includes('0.2') ||
    trimmed.includes('0.1') ||
    trimmed.includes('0.3')
  ) {
    return '#0f172a';
  }

  return fallback;
}

